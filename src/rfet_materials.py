# -*- coding: utf-8 -*-
"""
rfet_materials.py
================================================================================
STEP 3-A : 정전기(Poisson) 단계에 필요한 재료 물성 — 유전율만.
          (밴드갭, 유효질량, 일함수 등은 이동 전하를 넣는 STEP 4 이후에 별도 파일로 추가한다.)

각 값 위의 태그: [문헌값] 출처 명시 / [모델 가정] / [모델 단순화]

물리 모델과 수치 설정의 구분
  - 여기 있는 것은 전부 "물리 모델"(어떤 ε를 쓰는가)이다. 수치 설정은 하나도 없다.
  - Poisson 방정식  ∇·(ε ∇ψ) = -ρ  에서 ε 만 이 파일이 정한다. ρ 는 STEP 3에서 0 (아래 참조).
"""
import math

# ==============================================================================
# 섹션 1. 기본 상수
# ==============================================================================
# [문헌값] 진공 유전율 ε0 = 8.8541878128e-12 F/m (CODATA 2018, NIST: https://physics.nist.gov/cgi-bin/cuu/Value?ep0)
#   DEVSIM은 길이 단위로 cm를 쓰므로 F/cm 로 환산해 둔다: 1 F/m = 1e-2 F/cm
EPS0_F_PER_M = 8.8541878128e-12
EPS0_F_PER_CM = EPS0_F_PER_M * 1.0e-2          # = 8.854e-14 F/cm

# ==============================================================================
# 섹션 2. 2D 물질 유전율 — 이방성 값 그대로 기록
# ------------------------------------------------------------------------------
# [문헌값] A. Laturia, M. L. Van de Put, W. G. Vandenberghe,
#   "Dielectric properties of hexagonal boron nitride and transition metal dichalcogenides:
#    from monolayer to bulk", npj 2D Materials and Applications 2, 6 (2018).
#   DOI: 10.1038/s41699-018-0050-x   (공개본: https://par.nsf.gov/servlets/purl/10063423)
#   방법: DFT(VASP, PAW, PBE-GGA, Grimme vdW 보정) + DFPT. ε∞ = 전자 기여(광학), ε0 = 정적(이온 기여 포함).
#   단층 면외 값은 진공을 포함한 supercell에서 직렬 커패시터 식(식 1)으로 추출하며 층 두께 선택에 민감하다고
#   논문이 명시함 -> 다층/벌크 값이 단층 값보다 신뢰도가 높다.
#
#   Table 2 (WSe2, H상):  (⊥, ∥)
#     1L   : ε∞ = 7.5, 15.1   ε0 = 7.5, 15.3
#     2L   : ε∞ = 7.7, 15.2   ε0 = 7.7, 15.5
#     Bulk : ε∞ = 7.8, 15.7   ε0 = 7.9, 16.0
#   Table 1 (h-BN):  ε∥,∞  ε∥,0  ε⊥,∞  ε⊥,0
#     1L   : 4.97  6.82  2.89  3.29
#     2L   : 4.97  6.86  2.91  3.44
#     Bulk : 4.98  6.93  3.03  3.76
#
# 정전기 단계에서 정적값(ε0)을 쓰는 이유: 게이트 전압은 DC이므로 이온 분극까지 응답한다.
# ==============================================================================
LATURIA_2018 = {
    "WSe2": {"1L": {"perp": 7.5, "para": 15.3}, "2L": {"perp": 7.7, "para": 15.5}, "bulk": {"perp": 7.9, "para": 16.0}},
    "hBN":  {"1L": {"perp": 3.29, "para": 6.82}, "2L": {"perp": 3.44, "para": 6.86}, "bulk": {"perp": 3.76, "para": 6.93}},
}

# [문헌값] WSe2 단층 두께 6.52 Å — Laturia 2018, Table 3 (논문이 면외 ε 추출에 쓴 층 두께)
#   9.1 nm 박막의 층수 환산에만 쓴다. (2H-WSe2 벌크 c축 격자상수의 절반에 해당하는 값)
WSE2_LAYER_THICKNESS_NM = 0.652


def wse2_layer_count(t_nm):
    """두께 -> 층수 (반올림). 9.1 nm -> 14층."""
    return int(round(t_nm / WSE2_LAYER_THICKNESS_NM))


# 어느 층수 값을 쓸 것인가 (원칙 7: 단층 값을 다층에 그냥 쓰지 않는다)
#   WSe2 9.1 nm = 약 14층. Laturia 2018에서 면외 ε는 1L -> bulk 로 7.5 -> 7.9 (약 5%), 면내는 거의 불변.
#   14층은 이 변화가 포화된 영역이므로 bulk 값을 쓴다.
#   h-BN 30 nm = 약 90층(층간 3.33 Å 기준) -> bulk 값.  (h-BN 층간 거리 출처는 별도 확인 필요; 여기서는
#   "30 nm가 2층(0.67 nm)보다 훨씬 두껍다"는 사실만으로 bulk 선택이 정당화된다.)
WSE2_EPS = LATURIA_2018["WSe2"]["bulk"]       # {"perp": 7.9, "para": 16.0}
HBN_EPS = LATURIA_2018["hBN"]["bulk"]         # {"perp": 3.76, "para": 6.93}

# ==============================================================================
# 섹션 3. SiO2, 공기
# ==============================================================================
# [문헌값] SiO2 상대 유전율 3.9 — S. M. Sze, K. K. Ng, Physics of Semiconductor Devices, 3rd ed.
#   (Wiley, 2007), Appendix "Properties of SiO2 and Si3N4" (표에 εr = 3.9). 참고서(2차 문헌)이므로
#   STEP 1 분류로는 [B]에 준하되 "교과서 표준값"임을 명시한다. 열산화막 기준.
SIO2_EPS = 3.9

# [모델 단순화] 공기/진공 ε = 1.0 (공기의 실제 상대 유전율은 1에 매우 가까움, 차이 < 0.1%)
AIR_EPS = 1.0

# ==============================================================================
# 섹션 4. 스칼라 유전율 선택 (DEVSIM 기본 Poisson 이산화가 영역별 스칼라 ε 를 전제하기 때문)
# ------------------------------------------------------------------------------
# [모델 단순화] WSe2, h-BN 은 ε⊥ ≠ ε∥ 인데 스칼라 하나를 써야 한다면 어느 값을 쓸지 정해야 한다.
#   이 연구가 보는 것은 "게이트 -> 채널" 결합이고, 게이트 전기장은 박막을 면외(⊥) 방향으로 지난다.
#   따라서 baseline 스칼라값 = ε⊥ (정적). 면내 전기장(채널 방향 전위 기울기)에는 ε∥ 가 맞으므로,
#   스칼라 선택의 오차를 보기 위해 ε∥ 로 바꾼 계산을 민감도 비교로 함께 돌린다 (SCALAR_VARIANTS).
#   텐서 ε 를 그대로 쓰는 계산은 rfet_fem_reference.py(독립 FEM)에서 가능하므로, 세 결과
#   (ε⊥ 스칼라 / ε∥ 스칼라 / 텐서)를 비교하면 단순화의 영향을 숫자로 말할 수 있다.
# ==============================================================================
def scalar_eps(variant="perp"):
    """영역 이름 -> 상대 유전율 (스칼라). variant: 'perp' (baseline) 또는 'para' (민감도)."""
    return {
        "SiO2": SIO2_EPS,
        "WSe2": WSE2_EPS[variant],
        "AirBot": AIR_EPS,
        "AirTop": AIR_EPS,
        "hBN": HBN_EPS[variant],
    }


def tensor_eps():
    """영역 이름 -> (ε_xx, ε_yy). 2D 단면에서 x = 면내(채널 방향), y = 면외.
    [모델 단순화] 경사 구간(WSe2가 8도 기울어진 곳)에서도 주축을 x, y 로 둔다. 8도 회전에 의한
    비대각 성분은 sin(8°)·(ε∥-ε⊥)/2 ≈ 0.56 으로 작지만 0은 아니다. rfet_fem_reference.py 는
    회전된 텐서도 받을 수 있게 만들어 두었으므로 필요하면 경사 영역을 따로 나눠 넣을 수 있다."""
    return {
        "SiO2": (SIO2_EPS, SIO2_EPS),
        "WSe2": (WSE2_EPS["para"], WSE2_EPS["perp"]),
        "AirBot": (AIR_EPS, AIR_EPS),
        "AirTop": (AIR_EPS, AIR_EPS),
        "hBN": (HBN_EPS["para"], HBN_EPS["perp"]),
    }


SCALAR_VARIANTS = ("perp", "para")

# ==============================================================================
# 섹션 5. 전하밀도 — STEP 3 의 가정
# ------------------------------------------------------------------------------
# [모델 가정] ρ = 0 (모든 영역). WSe2 를 "이동 전하가 없는 유전체"로 본다.
#   근거: 첫 단계의 목적이 "전극 배치만으로 생기는 게이트 전기장의 선택적 도달"을 보는 것이므로,
#   전하가 전기장을 가리는 효과(screening)를 일부러 뺀다. 이 때문에 실제보다 게이트 전기장이
#   박막 안으로 더 깊이 들어온다(과대평가). 또한 ρ = 0 이면 Poisson이 선형이라
#   ψ = Σ_i V_i · ψ_i (게이트 i 에 1 V 걸고 나머지 0 V 일 때의 해) 로 중첩된다. 금속 일함수 차이는
#   각 접점의 상수 오프셋이므로 "전압 변화에 대한 응답" dψ/dV 에는 영향을 주지 않는다 -> STEP 3 에서는 0.
#   계면 고정전하, 트랩 전하도 0 으로 둔다 (논문에 값 없음).
# ==============================================================================
RHO_MODEL = "zero"


if __name__ == "__main__":
    print(f"WSe2 9.1 nm = 약 {wse2_layer_count(9.1)} 층 (층 두께 {WSE2_LAYER_THICKNESS_NM} nm, Laturia 2018 Table 3)")
    print("스칼라 ε (baseline, ⊥):", scalar_eps("perp"))
    print("스칼라 ε (민감도, ∥):  ", scalar_eps("para"))
    print("텐서 ε (xx, yy):       ", tensor_eps())
    print(f"ε0 = {EPS0_F_PER_CM:.4e} F/cm")
